package agent

import (
	"context"

	"github.com/Autumn-27/artex/db"
)

// FindingRecorder is injected by the host; agents never synthesize or copy
// evidence bodies themselves. Its implementation owns the atomic write.
type FindingRecorder interface {
	Record(context.Context, db.RecordFindingInput, []db.TrafficRef) (*db.RecordedFinding, error)
}

// Tool-use guidance is appended without replacing the user's editable prompt.
// It does not require capture or claim that unavailable traffic tools exist.
const findingTrafficGuidance = "\n\n**Vulnerability traffic evidence (optional)**: When calling report_finding to report a vulnerability, if you have viewed and confirmed HTTP requests/responses that support the vulnerability conclusion, you can use traffic_refs to bind the real IDs in reproduction order; domain and time are only used for candidate filtering, and associations are not inferred. For non-HTTP vulnerabilities such as TCP, or when not collected or no exact match exists, omit it or pass [], keep other verifiable evidence such as command output and logs in evidence, and it is recommended to explain why no binding was made. Do not guess IDs, and do not repeat probing just to supplement packets."

func (t *ToolSet) SetFindingRecorder(r FindingRecorder)   { t.findingRecorder = r }
func (w *Worker) SetFindingRecorder(r FindingRecorder)    { w.findingRecorder = r }
func (p *Planner) SetFindingRecorder(r FindingRecorder)   { p.findingRecorder = r }
func (m *MainAgent) SetFindingRecorder(r FindingRecorder) { m.findingRecorder = r }
