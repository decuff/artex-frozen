// TestNotifyDigestSegmentsAndDefersRemainder is the end-to-end evidence for the 'silent loss' fix.
//
// The digest message is constrained by the channel length limit (WeCom 4096 bytes); when a batch doesn't fit, it must be split **by whole entries**:
// the entries packed into this message are marked as delivered, and the rest go back to the queue to wait for the next message. The old implementation marked the whole batch
// as successful—the truncated ones were neither in the message nor in the failure list, and the delivery history still showed success,
// so the bug just vanished.
//
// Assert four things: ① only the number of entries actually packed were marked ② the rest are still pending ③ the deferred entries
// **did not consume retry attempts** ④ another round can send out the remainder (no deadlock).
func TestNotifyDigestSegmentsAndDefersRemainder(t *testing.T) {
	f := newNotifyFixture(t)
	hook := newFakeWebhook(t)
	// Use WeCom: markdown limit is 4096 bytes, the tightest of the six channels.
	chID := f.createChannel(t, map[string]any{
		"name":   "segmented digest",
		"kind":   notify.KindWeCom,
		"mode":   db.NotifyModeDigest,
		"config": map[string]any{"webhook": hook.URL},
	})
	const total = 60
	// Make the title longer to ensure 60 entries far exceed 4096 bytes and must be segmented.
	longName := strings.Repeat("extra-long vulnerability name", 6)
	for i := 0; i < total; i++ {
		f.record(t, longName+strconv.Itoa(i+1), "high")
	}
	ctx := context.Background()
	if _, _, err := f.pg.FanOutPendingEvents(ctx, 500); err != nil {
		t.Fatal(err)
	}
	f.agePendingBatch(t, chID)
	ch := f.channel(t, chID)

	f.n.stepDigest(ctx, ch, 50, "")
	if hook.count() != 1 {
		t.Fatalf("should send only one message, got %d", hook.count())
	}

	var sent, pending int
	if err := f.pg.QueryRow(`SELECT
    count(*) FILTER (WHERE state=$2),
    count(*) FILTER (WHERE state=$3)
  FROM notification_deliveries WHERE channel_id=$1`, chID, db.NotifyStateSent, db.NotifyStatePending).
		Scan(&sent, &pending); err != nil {
		t.Fatal(err)
	}
	if sent == 0 {
		t.Fatal("some entries should be marked as delivered")
	}
	if pending == 0 {
		t.Fatalf("a batch of %d entries cannot all fit in 4096 bytes, there should be remaining pending; sent=%d", total, sent)
	}
	if sent+pending != total {
		t.Fatalf("entry counts don't add up: sent=%d pending=%d total=%d (neither delivered nor pending = lost)", sent, pending, total)
	}
	// The message body must truthfully state how many entries are not included in this message.
	if text := markdownText(t, hook.last(t)); !strings.Contains(text, "remaining") {
		t.Fatalf("the message should state that some entries are not included in this message:\n%.400s", text)
	}

	// Deferred entries must not consume the retry budget: attempts is optimistically +1 on claim, and must be decremented back on deferral.
	var maxAttempts int
	if err := f.pg.QueryRow(`SELECT COALESCE(max(attempts),0) FROM notification_deliveries
WHERE channel_id=$1 AND state=$2`, chID, db.NotifyStatePending).Scan(&maxAttempts); err != nil {
		t.Fatal(err)
	}
	if maxAttempts > 0 {
		t.Fatalf("deferred entries should not consume retry attempts (otherwise they'd be marked failed after a few), got attempts=%d", maxAttempts)
	}

	// Run repeatedly until convergence. What's asserted is **eventual full delivery** and that it genuinely took multiple rounds—
	// this is stronger than 'sent in the second round': it proves segmentation doesn't deadlock and doesn't drop the remaining entries.
	rounds := 0
	for {
		var undelivered int
		if err := f.pg.QueryRow(`SELECT count(*) FROM notification_deliveries
WHERE channel_id=$1 AND state <> $2 AND state <> $3`, chID, db.NotifyStateSent, db.NotifyStateFailed).
			Scan(&undelivered); err != nil {
			t.Fatal(err)
		}
		if undelivered == 0 {
			break
		}
		rounds++
		if rounds > total+5 {
			t.Fatalf("segmented delivery does not converge: after %d rounds there are still %d undecided", rounds, undelivered)
		}
		before := hook.count()
		f.n.stepDigest(ctx, ch, 50, "")
		if hook.count() == before {
			t.Fatalf("round %d made no progress, the remaining %d entries will be stuck forever", rounds, undelivered)
		}
	}
	if rounds < 2 {
		t.Fatalf("a single 4096-byte message cannot fit %d long-title vulnerabilities, it should be sent over multiple rounds, but only took %d rounds", total, rounds)
	}
	// Every round after the first should be a **pure continuation**, with no entries rejected by the channel.
	var failed int
	if err := f.pg.QueryRow(`SELECT count(*) FROM notification_deliveries WHERE channel_id=$1 AND state=$2`,
		chID, db.NotifyStateFailed).Scan(&failed); err != nil {
		t.Fatal(err)
	}
	if failed != 0 {
		t.Fatalf("The fake receiver always returns success, so there should be no failed entries, got %d", failed)
	}
}

// TestNotifyBackoffTableMatchesAttemptBudget is a drift-prevention assertion.
//
// The retry budget (db.MaxNotifyAttempts) and the backoff sequence table (notifyBackoff) live in two packages:
// the former is the state machine's policy, the latter is the engine's execution cadence. If only one is changed—say, the budget is raised to 5
// attempts but the backoff tiers are forgotten—the code won't error, it will just make the 4th and 5th retries reuse the last tier's interval,
// manifesting as 'retry cadence mysteriously slowing down', which is hard to connect to this spot when troubleshooting.
// Assert that both lengths match, so this drift is exposed in CI.
func TestNotifyBackoffTableMatchesAttemptBudget(t *testing.T) {
	if len(notifyBackoff) != db.MaxNotifyAttempts {
		t.Fatalf("Backoff tier count (%d) and max attempt count (%d) are inconsistent—changing one requires changing the other",
			len(notifyBackoff), db.MaxNotifyAttempts)
	}
	// Backoff intervals must be monotonically non-decreasing, otherwise retries get more aggressive, worsening rate limiting.
	for i := 1; i < len(notifyBackoff); i++ {
		if notifyBackoff[i] < notifyBackoff[i-1] {
			t.Fatalf("Backoff intervals must be monotonically non-decreasing: tier %d %v < tier %d %v",
				i, notifyBackoff[i], i-1, notifyBackoff[i-1])
		}
	}
}

// TestNotifyRateLimitDoesNotConsumeRetryBudget locks in the order of 'take token first, then claim'.
// If reversed (claim first, then discard), deliveries blocked by rate limiting have already counted an attempt,
// the budget gets exhausted by pure waiting, and they end up in failed.
func TestNotifyRateLimitDoesNotConsumeRetryBudget(t *testing.T) {
	// Test only the token bucket itself, no Server needed (and none should be built for it).
	n := &Notifier{buckets: map[int64]*notifyBucket{}}
	now := time.Now()
	// 1 per minute: at most 1 when the bucket is full.
	if got := n.takeTokens(1, 1, notifyMaxSendsPerChannelPerTick, now); got != 1 {
		t.Fatalf("At 1 per minute with a full bucket, 1 token should be taken, got %d", got)
	}
	if got := n.takeTokens(1, 1, notifyMaxSendsPerChannelPerTick, now.Add(time.Millisecond)); got != 0 {
		t.Fatalf("After tokens are exhausted, 0 should be returned immediately, got %d", got)
	}
	if got := n.takeTokens(1, 1, notifyMaxSendsPerChannelPerTick, now.Add(30*time.Second)); got != 0 {
		t.Fatalf("Halfway through, a token should not be replenished, got %d", got)
	}
	if got := n.takeTokens(1, 1, notifyMaxSendsPerChannelPerTick, now.Add(time.Minute)); got != 1 {
		t.Fatalf("After one full period, 1 token should be replenished, got %d", got)
	}
	// Unlimited channels use a finite cap, avoiding a single round being stalled by unbounded backlog.
	if got := n.takeTokens(2, 0, notifyUnlimitedBurstPerTick+10, now); got != notifyUnlimitedBurstPerTick {
		t.Fatalf("Unlimited should return the per-round cap %d, got %d", notifyUnlimitedBurstPerTick, got)
	}
	// Token buckets are independent between channels.
	if got := n.takeTokens(1, 1, notifyMaxSendsPerChannelPerTick, now.Add(time.Millisecond)); got != 0 {
		t.Fatalf("Channel 1's bucket should still be empty, got %d", got)
	}
}

// TestNotifyTakeTokensKeepsUnusedTokens locks in the semantics of 'take only want tokens'.
//
// The previous implementation drained the entire bucket before the caller truncated it, so a channel with rate=100/min would fill up the bucket,
// Only 5 are used per round, and the remaining 95 tokens are simply discarded; the same deduction applies when the channel has no pending deliveries this round.
// The result is that the comment's claim of 'when there is a backlog, rate_per_min entries can be flushed all at once' cannot be achieved under any circumstances.
func TestNotifyTakeTokensKeepsUnusedTokens(t *testing.T) {
	n := &Notifier{buckets: map[int64]*notifyBucket{}}
	now := time.Now()
	// The bucket starts full (100), and this round only needs 5.
	if got := n.takeTokens(1, 100, 5, now); got != 5 {
		t.Fatalf("when want=5, exactly 5 tokens should be taken, got %d", got)
	}
	// Key assertion: the remaining 95 must still be in the bucket, not drained and discarded.
	// Do not advance time, ensuring that what is fetched can only come from existing stock rather than replenishment.
	if got := n.takeTokens(1, 100, 95, now); got != 95 {
		t.Fatalf("remaining tokens should still be available (expected 95), got %d — the bucket was drained entirely", got)
	}
	if got := n.takeTokens(1, 100, 1, now); got != 0 {
		t.Fatalf("bucket exhausted, should return 0, got %d", got)
	}
	// want<=0 should not deduct any tokens (empty rounds are free).
	n2 := &Notifier{buckets: map[int64]*notifyBucket{}}
	if got := n2.takeTokens(1, 20, 0, now); got != 0 {
		t.Fatalf("want=0 should return 0, got %d", got)
	}
	if got := n2.takeTokens(1, 20, 20, now); got != 20 {
		t.Fatalf("the call where want=0 should not consume a token and should still get the full 20, got %d", got)
	}
}

// TestDigestTickPlanDecouplesBatchSizeFromSendBudget pins down the two dimensions of summary mode.
//
// Once the summary batch size is tied to the per-round request budget, a channel with rate_per_min=20 can only, in each
// In the 3-second tick, only 1 token is replenished, so each summary message holds only 1 vulnerability—functionally equivalent to none
// summary, while the message header still says '1 new vulnerability in the last 30 minutes'. This degradation does not raise an error,
// The existing end-to-end test cases don't reveal it either (they manually pass a sufficiently large limit to stepDigest,
// bypassed the quota calculation in the step), so here we directly assert the decision itself.
func TestDigestTickPlanDecouplesBatchSizeFromSendBudget(t *testing.T) {
	tokens, claimLimit := digestTickPlan()
	// One batch = one message = one request = one token. The unit of a token is a message, not a vulnerability.
	if tokens != 1 {
		t.Fatalf("A batch summary sends only one message, so it should consume exactly 1 token, got %d", tokens)
	}
	if claimLimit != db.MaxDigestBatchSize {
		t.Fatalf("summary batch size should be the memory upper bound db.MaxDigestBatchSize=%d, got %d",
			db.MaxDigestBatchSize, claimLimit)
	}
	// Key relationship: batch size must be much larger than the per-round request budget. Once the two are of the same order of magnitude,
	// The explanation again conflates 'how many messages to send' and 'how many vulnerabilities to pack in one batch' into a single number.
	if claimLimit <= notifyMaxSendsPerChannelPerTick {
		t.Fatalf("aggregate batch size %d should not be constrained by per-round request budget %d——"+
			"The request budget is derived backwards from the lease as 'how many requests to send', which is a different dimension from 'how many vulnerabilities to pack in one batch'",
			claimLimit, notifyMaxSendsPerChannelPerTick)
	}
}

// TestNotifyTickBudgetFitsWithinLease is yet another anti-drift assertion.
//
// The per-tick delivery cap for a single channel (notifyMaxSendsPerChannelPerTick) is derived backwards from the lease duration:
// the worst-case time for serial delivery within one tick must be < the lease, otherwise the lease expires before the last few are sent,
// and in a multi-instance deployment the peer will re-claim them and send duplicates. These three constants live in different places,
// and changing any one of them can break the relationship without any error—so we pin it down here.
func TestNotifyTickBudgetFitsWithinLease(t *testing.T) {
	worst := time.Duration(notifyMaxSendsPerChannelPerTick) * notifySendTimeout
	if worst >= notifyLease {
		t.Fatalf("the worst-case time for a single channel per tick %v should not reach or exceed the lease %v"+
			"（notifyMaxSendsPerChannelPerTick=%d × notifySendTimeout=%v）——"+
			"changing any one of these three constants requires checking the other two in sync",
			worst, notifyLease, notifyMaxSendsPerChannelPerTick, notifySendTimeout)
	}
}
