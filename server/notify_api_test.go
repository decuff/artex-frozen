// This file covers the end-to-end behavior of the push feature: vulnerability persisted → event → dispatch → actually send HTTP.
//
// A security note: these cases **do not call the global Notifier.step()**, only for the channels they create
// they call stepRealtime/stepDigest. The reason is that step() iterates over all enabled channels in the database—
// running tests on a dev database already configured with real DingTalk/WeCom bots, the global step would push vulnerabilities
// generated during the test to those groups for real. Calling per-channel strictly limits the impact to the fake receivers created by the test.
//
// Cleanup: at the end of the case, delete the events generated by this case (cascade deletes deliveries) and channels, leaving no backlog for real channels.
//
// Assertion approach: stepRealtime/stepDigest return no value and log internally, so what is asserted here is
// **observable external behavior** (what the fake receiver received, what state the delivery rows ended up in), not the function's
// return value—this is closer to the real call path than stubbing the return value.

// notifyFixture is the common fixture for the cases in this file.
type notifyFixture struct {
	s       *Server
	pg      *db.DB
	request func(method, path, body string) *httptest.ResponseRecorder
	n       *Notifier
	// Self-created task/exploration: the case records vulnerabilities here, isolated from other cases' data.
	taskID int64
	expID  int64
	// Events generated after cleanupMark are also deleted during cleanup.
	cleanupMark int64
}

func newNotifyFixture(t *testing.T) *notifyFixture {
	t.Helper()
	// All fake receivers in this file run on 127.0.0.1, and delivery rejects loopback addresses by default
	// (to prevent SSRF from hitting same-machine services and cloud metadata). The test explicitly turns this switch on;
	// the behavior of the 'reject by default' guard is covered by ssrf_test.go in the notify package.
	t.Setenv(notify.AllowLocalTargetsEnv, "1")
	s, _, request := trafficEvidenceServer(t)
	pg := s.m.pg

	// Create a task ourselves: the task created by the shared fixture trafficEvidenceServer cannot get an exploration id,
	// and recording a vulnerability must provide it.
	task, err := s.m.CreateTask("Notification push test", "Push behavior verification", nil, 0, 0)
	if err != nil {
		t.Fatal(err)
	}
	taskID, err := strconv.ParseInt(task.ID, 10, 64)
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() { pg.Exec(`DELETE FROM tasks WHERE id=$1`, taskID) })

	var mark int64
	if err := pg.QueryRow(`SELECT COALESCE(max(id),0) FROM notification_events`).Scan(&mark); err != nil {
		t.Fatal(err)
	}
	// Make the fixture self-contained: mark events that existed before the fixture was created as already dispatched in one go.
	//
	// Why this is necessary: FanOutPendingEvents is **global**, and will expand all undispatched events in the database
	// onto all matching channels. And the shared fixture trafficEvidenceServer itself records a vulnerability
	// (exactly the initial finding it returns), and other cases may also have leftovers. Without isolation,
	// these stray events would be dispatched to this case's channels, making assertions like 'there should be N deliveries'
	// pass sometimes and fail other times—and the failure mode depends on case execution order, which is harder to debug than a direct failure.
	if _, err := pg.Exec(`UPDATE notification_events SET fanned_out = true WHERE id <= $1 AND NOT fanned_out`, mark); err != nil {
		t.Fatal(err)
	}

	f := &notifyFixture{s: s, pg: pg, request: request, n: newNotifier(s), taskID: taskID, expID: task.ExpID, cleanupMark: mark}
	t.Cleanup(func() {
		if _, err := pg.Exec(`DELETE FROM notification_events WHERE id > $1`, f.cleanupMark); err != nil {
			t.Logf("Failed to clean up notification events: %v", err)
		}
	})
	// The master switch must be on (other test cases may have turned it off).
	if err := pg.SetBool(settingNotifyEnabled, true); err != nil {
		t.Fatal(err)
	}
	return f
}

// record goes through the real evidence-writing path to persist a vulnerability and returns the finding id.
// This path registers the push event in the **same transaction** — which is exactly the hook point of this feature.
func (f *notifyFixture) record(t *testing.T, vulnclass, severity string) int64 {
	t.Helper()
	out, err := f.s.evidenceStore().Record(context.Background(), db.RecordFindingInput{
		TaskID:        f.taskID,
		ExplorationID: f.expID,
		Worker:        "test",
		VulnClass:     vulnclass,
		Name:          vulnclass,
		Severity:      severity,
		Summary:       vulnclass + " summary",
		Evidence:      "poc",
	}, nil)
	if err != nil {
		t.Fatalf("failed to record vulnerability: %v", err)
	}
	return out.FindingID
}

